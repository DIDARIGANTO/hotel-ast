export function translate(key, lang) {
  const dict = DICT[lang] ?? DICT.ru;
  if (key in dict) return dict[key];
  if (key in DICT.ru) {
    console.warn(`i18n: нет перевода "${key}" для языка "${lang}"`);
    return DICT.ru[key];
  }
  console.warn(`i18n: неизвестный ключ "${key}"`);
  return key;
}

const STORAGE_KEY = 'ast-lang';

// Язык задаёт папка адреса: /kk/ и /en/ — отдельные статические версии,
// корень — русская. Параметр ?lang= оставлен для старых ссылок.
export function langFromPath() {
  const m = location.pathname.match(/\/(kk|en)\//);
  return m ? m[1] : null;
}

export function currentLang() {
  const fromPath = langFromPath();
  if (fromPath) return fromPath;
  const fromUrl = new URLSearchParams(location.search).get('lang');
  if (LANGS.includes(fromUrl)) return fromUrl;
  return 'ru';
}

// Адрес той же страницы на другом языке.
export function pageUrlFor(lang) {
  const path = location.pathname.replace(/\/(kk|en)\//, '/');
  const file = path.split('/').pop() || 'index.html';
  const base = path.slice(0, path.length - file.length);
  const name = file === '' ? 'index.html' : file;
  return lang === 'ru' ? `${base}${name}` : `${base}${lang}/${name}`;
}

export function applyLang(lang) {
  document.documentElement.lang = lang === 'kk' ? 'kk' : lang;
  localStorage.setItem(STORAGE_KEY, lang);

  // Если ключа нет ни в одном словаре, в разметке уже лежит нормальный
  // русский текст — он лучше, чем показанный гостю служебный ключ.
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const value = translate(node.dataset.i18n, lang);
    if (value !== node.dataset.i18n) node.textContent = value;
  });

  // data-i18n-attr="placeholder:booking.name"
  document.querySelectorAll('[data-i18n-attr]').forEach((node) => {
    node.dataset.i18nAttr.split(';').forEach((pair) => {
      const [attr, key] = pair.split(':');
      if (attr && key) node.setAttribute(attr.trim(), translate(key.trim(), lang));
    });
  });

  document.querySelectorAll('.lang button').forEach((btn) => {
    btn.classList.toggle('is-active', btn.dataset.lang === lang);
  });

  // Карточки отелей и номеров рисует pages.js — сообщаем ему о смене языка.
  document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
}

export function initI18n() {
  applyLang(currentLang());
  document.querySelectorAll('.lang button').forEach((btn) => {
    btn.addEventListener('click', () => {
      const lang = btn.dataset.lang;
      if (lang === currentLang()) return;
      location.href = pageUrlFor(lang);
    });
  });
}

document.addEventListener('DOMContentLoaded', initI18n);
